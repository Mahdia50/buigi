const letters = ["A", "B", "C", "D"];

function hash(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

function build(catId, catName, points, n, question, answer, wrongs, explain) {
  const pool = [...new Set(wrongs.filter((w) => w && w !== answer))].slice(0, 3);
  while (pool.length < 3) pool.push(`خيار ${pool.length + 1}`);
  const items = [answer, pool[0], pool[1], pool[2]];
  const order = [0, 1, 2, 3];
  let h = hash(question);
  for (let i = order.length - 1; i > 0; i--) {
    h = (h * 1664525 + 1013904223) >>> 0;
    const j = h % (i + 1);
    [order[i], order[j]] = [order[j], order[i]];
  }
  const options = {};
  order.forEach((src, i) => { options[letters[i]] = items[src]; });
  const correct = letters[order.indexOf(0)];
  const id = `ex_${catId}_${points}_${n}`;
  return {
    id,
    points,
    value: points,
    difficulty: points <= 200 ? "easy" : points <= 400 ? "medium" : "hard",
    question_type: "text",
    media: null,
    question,
    options,
    correct_answer: correct,
    explanation: explain,
    source_title: "سين المغرب",
    source_url: "",
    category: catName,
    category_id: catId,
    text: question,
    image: "",
    answer,
    explain,
  };
}

function fromRows(catId, catName, rows, specs) {
  const out = [];
  for (const row of rows) {
    for (const spec of specs) {
      const answer = row[spec.key];
      if (!answer) continue;
      const wrongs = rows.map((r) => r[spec.key]).filter((v) => v && v !== answer);
      out.push({ q: spec.q(row), a: answer, w: wrongs, e: spec.e(row) });
    }
  }
  return out.slice(0, 80).map((item, i) => {
    const points = [100, 200, 300, 400, 500][i % 5];
    return build(catId, catName, points, i + 1, item.q, item.a, item.w, item.e);
  });
}

